"""Physical ionization energies from Cloudy's identified NIST ASD snapshot.

Outer-shell thresholds and ionization energy budgets use these energies.
Inner-shell PH1 edges and Voronov reaction-fit parameters remain independent.
No production files are written on import.
"""
from pathlib import Path
import hashlib
import math

from atomic_output import atomic_write_text

HC_EV_CM = 1.2398419843320026e-4
SOURCE = Path.home()/'CLOUDY/c25.00/data/ionization_potentials.dat'
ELEMENTS = [('c',6),('n',7),('o',8),('ne',10),('s',16),('ar',18),
            ('mg',12),('fe',26),('si',14),('cl',17),('ca',20)]


def read_ionization_potentials(path=SOURCE):
    """Return {(Z, bound_electrons): physical ionization energy [eV]}."""
    path = Path(path)
    lines = path.read_text().splitlines()
    if lines[0].split()[0] != '20221115':
        raise ValueError('Unreviewed ionization-potential snapshot: '+str(path))
    result = {}
    for number,line in enumerate(lines[1:],2):
        if line.lstrip().startswith('*'):
            break
        fields = line.split('#',1)[0].split()
        if not fields:
            continue
        if len(fields) != 4:
            raise ValueError(f'{path}:{number}: invalid energy record')
        z,charge = map(int,fields[:2])
        energy,uncertainty = map(float,fields[2:])
        key = (z,z-charge)
        if not 1 <= z <= 118 or not 0 <= charge < z or key in result:
            raise ValueError(f'{path}:{number}: invalid or duplicate ion identity')
        if not math.isfinite(energy) or energy <= 0 or not math.isfinite(uncertainty) or uncertainty < 0:
            raise ValueError(f'{path}:{number}: invalid energy or uncertainty')
        result[key] = energy*HC_EV_CM
    return result


def write_metal_ionization_module(path):
    """Record the supported physical energies for the terminal-stage check."""
    energies = read_ionization_potentials()
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    lines = ['module metal_ionization_potential_mod',
             '! Physical ionization energies [eV], NIST ASD snapshot 2022-11-15.',
             '! Source: Cloudy c25.00 data/ionization_potentials.dat.',
             '! SHA-256: '+digest,
             '! Generated by tools/fitting/ionization_potentials.py.',
             '! No cross-section or collision-fit thresholds are replaced here.',
             '  use define, only: wp, MAX_ION_STAGES',
             '  implicit none', '  private',
             '  public :: metal_ionization_potential',
             '  integer, parameter :: atomic_numbers(11) = [6,7,8,10,16,18,12,26,14,17,20]',
             '  real(kind=wp), parameter :: potentials(MAX_ION_STAGES,11) = reshape([ &']
    for index,(name,z) in enumerate(ELEMENTS):
        values = [energies.get((z,z-stage+1),-1.) for stage in range(1,8)]
        for offset in range(0,7,3):
            subset = values[offset:offset+3]
            last = index==10 and offset==6
            lines.append('       '+', '.join(f'{v:.16e}_wp' for v in subset)+(' & ' if last else ', &'))
    lines += ['       ], [MAX_ION_STAGES,11])', 'contains',
              '  real(kind=wp) function metal_ionization_potential(Z, stage) result(energy)',
              '    integer, intent(in) :: Z, stage', '    integer :: element',
              '    energy = -1.0_wp',
              '    do element = 1, size(atomic_numbers)',
              '       if (Z /= atomic_numbers(element)) cycle',
              '       if (stage == Z+1) then',
              '          energy = huge(1.0_wp) ! Fully stripped: no further ionization.',
              '       else if (stage >= 1 .and. stage <= MAX_ION_STAGES) then',
              '          energy = potentials(stage,element)',
              '       end if', '       return', '    end do',
              '  end function metal_ionization_potential',
              'end module metal_ionization_potential_mod']
    atomic_write_text(path,'\n'.join(lines)+'\n')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fortran-module',type=Path,required=True)
    args = parser.parse_args()
    write_metal_ionization_module(args.fortran_module)
