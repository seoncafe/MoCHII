"""Measure effects of removing above-threshold states from bound line cooling."""
import argparse
import json
from pathlib import Path
from unittest.mock import patch
import numpy as np
import chianti_cooling as C
from atomic_output import atomic_write_text


def original_atom(element,stage):
    raw,rad,coll=C.read_excitation_atom(element,stage)
    return C.selected_energies(element,stage,raw,rad,coll),rad,coll


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output-dir',type=Path,required=True)
    args=p.parse_args();args.output_dir.mkdir(parents=True,exist_ok=True)
    temperature=np.geomspace(1e3,1e5,801);saved={'temperature_K':temperature};records=[]
    paths=sorted(Path('data/atomic').glob('cooling_*_*.txt'))
    for path in paths:
        fields=path.stem.split('_')
        if len(fields)!=3 or not fields[-1].isdigit():continue
        _,element,number=fields;stage=int(number)
        if element=='h':continue
        raw,rad,coll=original_atom(element,stage);bound,brad,bcoll=C.bound_excitation_atom(element,stage)
        changed=[tr for tr in coll if tr['ll'] not in bound or tr['ul'] not in bound]
        if not changed:continue
        # The original all-level prescription is retained only for measuring
        # the defect; no claim of physical bound-state accuracy is made for it.
        with patch.object(C,'bound_excitation_atom',return_value=(raw,rad,coll)):
            previous=C.cooling_low_density_limit(element,stage,temperature)
        corrected=C.cooling_low_density_limit(element,stage,temperature)
        mask=previous>64*np.finfo(float).tiny;difference=corrected[mask]/previous[mask]-1
        record=dict(element=element,stage=stage,original_levels=len(raw),bound_connected_levels=len(bound),
            excluded_collision_pairs=len(changed),minimum_relative_change=float(difference.min()),
            maximum_relative_change=float(difference.max()),production_product=str(path),
            stale=bool(np.any(difference!=0)))
        records.append(record);saved[f'{element}_{stage}_original']=previous;saved[f'{element}_{stage}_bound']=corrected
    np.savez_compressed(args.output_dir/'profiles.npz',**saved)
    result=dict(passed=True,records=records,temperature_samples=801,temperature_K=[1000,100000],
        meaning='Source correction diagnostic; product values have not been regenerated by this script')
    atomic_write_text(args.output_dir/'result.json',json.dumps(result,indent=2)+'\n');print(json.dumps(result,indent=2))


if __name__=='__main__':main()
